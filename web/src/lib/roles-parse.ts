export type ParsedRole = { title: string; mustHaves: string };

const SKIP_TITLE =
  /^(location|industry|company size|links|open positions.*|engineering|design|product|sales|marketing|more jobs|jobs powered by|about|apply|careers|all jobs)$/i;

const LOCATION_LINE = /^(hybrid|remote|onsite|on-site|in[- ]office)\b|^\([^)]+\)$/i;

function cleanTitle(raw: string): string {
  return raw.replace(/^#+\s*/, "").replace(/\s+/g, " ").trim();
}

/** Drop careers-page junk so pitches don't say "hiring for Open Positions and US & HCM". */
export function usableRoleTitle(title: string): boolean {
  const t = title.replace(/\s+/g, " ").trim();
  if (!t || SKIP_TITLE.test(t)) return false;
  if (/^(us|uk|emea|apac|na|nyc|sf)\b/i.test(t) && !/\b(engineer|manager|designer|executive|scientist|recruiter|analyst|lead|director|marketer)\b/i.test(t)) {
    return false;
  }
  return true;
}

function isJobTitle(title: string): boolean {
  if (title.length < 3 || title.length > 80) return false;
  if (SKIP_TITLE.test(title)) return false;
  if (/[.!?]$/.test(title)) return false;
  if (title.split(" ").length > 12) return false;
  return /[A-Za-z]/.test(title);
}

/** Careers index pages: a title line followed by Hybrid / Remote / Onsite. */
export function parseCareersPage(markdown: string): ParsedRole[] {
  const lines = markdown
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  const jobs: ParsedRole[] = [];
  const seen = new Set<string>();

  for (let i = 0; i < lines.length - 1; i++) {
    const title = cleanTitle(lines[i]);
    const next = lines[i + 1];
    if (!LOCATION_LINE.test(next) || !isJobTitle(title)) continue;
    const key = title.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    jobs.push({ title, mustHaves: "" });
  }

  if (jobs.length) return jobs.slice(0, 40);

  for (const m of markdown.matchAll(/^#{1,3}\s+(.+)$/gm)) {
    const title = cleanTitle(m[1]);
    if (!isJobTitle(title) || seen.has(title.toLowerCase())) continue;
    seen.add(title.toLowerCase());
    jobs.push({ title, mustHaves: "" });
  }
  return jobs.slice(0, 40);
}

export function parseJobPostings(text: string): ParsedRole[] {
  const trimmed = text.trim();
  if (!trimmed) return [];

  const fromListing = parseCareersPage(trimmed);
  if (fromListing.length >= 2) return fromListing;

  const blocks = trimmed.split(/\n---+\n|\n(?=#{1,3}\s)/).map((b) => b.trim()).filter(Boolean);
  return blocks
    .map((block) => {
      const lines = block.split("\n");
      const title = cleanTitle(lines[0]);
      return { title, mustHaves: descriptionFromJobPage(block, title) };
    })
    .filter((b) => isJobTitle(b.title));
}

export function guessTitlesFromCareersPage(markdown: string): string[] {
  return parseCareersPage(markdown).map((r) => r.title);
}

const ROLE_HEAD =
  /^(?:position overview|about the role|the role|the opportunity|what you(?:'|’)ll do|what you will do|what we(?:'|’)re looking for|what we are looking for|key responsibilities|responsibilities|minimum qualifications|qualifications|requirements|preferred(?:\s*\(|\s|$)|nice[- ]to[- ]have|your background|about you)\b/i;

const STOP_HEAD =
  /^(?:similar jobs|about the company|about us|about [A-Z][\w.&+-]*|who we are|our story|benefits|how to apply|apply now|the company|what you need to know|jobs powered|share this|other openings|more jobs|our values|open positions)\b/i;

const META = /^(location|industry|company size|links)$/i;

const NOISE =
  /generated by ai|jobs powered by|by applying|sign up|create an account|apply for this job|^apply\b/i;

function plainLine(line: string): string {
  return line
    .replace(/^#{1,6}\s*/, "")
    .replace(/^\*+/, "")
    .replace(/\*+$/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function norm(value: string): string {
  return plainLine(value).toLowerCase();
}

function titleIn(haystack: string, title: string): boolean {
  const h = norm(haystack);
  const t = norm(title);
  if (!h || !t) return false;
  const escaped = t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?:^|[^a-z0-9])${escaped}(?:[^a-z0-9]|$)`).test(h);
}

function isCompanyPitch(line: string): boolean {
  const plain = plainLine(line);
  if (!plain || ROLE_HEAD.test(plain)) return false;
  if (/^we(?:'|’)?re looking for\b/i.test(plain) || /^we need\b/i.test(plain)) return false;
  if (/\b(you(?:'|’)ll|you will|years of|experience with|proficien|qualif|requir|must have|nice to have|responsib)\b/i.test(plain)) {
    return false;
  }
  if (/^(we|our|tinyfish)\b/i.test(plain)) return true;
  return /\b(our mission|about us|about the company|powers an|founded in|we(?:'|’)re here|one of the hardest|if it were easy|someone else would)\b/i.test(plain);
}

function isNoise(line: string): boolean {
  const plain = plainLine(line);
  if (!plain || /^-{3,}$/.test(plain) || /^view all jobs$/i.test(plain)) return true;
  if (META.test(plain) || LOCATION_LINE.test(plain) || NOISE.test(plain)) return true;
  return isCompanyPitch(line);
}

/** A careers index lists many jobs. It is not a description of any one of them. */
export function isCareersIndex(markdown: string): boolean {
  const lines = markdown
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .slice(0, 80);
  const hybrid = lines.filter((l) => LOCATION_LINE.test(plainLine(l))).length;
  const hasOpenings = lines.some((l) => /^open positions\b/i.test(plainLine(l)));
  const hasCompanyMeta = lines.some((l) => /^(industry|company size)$/i.test(plainLine(l)));
  const hasRoleSection = lines.some((l) => ROLE_HEAD.test(plainLine(l)));
  if (hasOpenings && hybrid >= 2) return true;
  if (!hasRoleSection && hasCompanyMeta && hybrid >= 2) return true;
  if (!hasRoleSection && hybrid >= 4) return true;
  return false;
}

function pageLines(markdown: string): string[] {
  return markdown
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
}

function collectRoleLines(lines: string[], start: number): string[] {
  const out: string[] = [];
  let i = start;
  while (i < lines.length) {
    const plain = plainLine(lines[i]);
    if (i > start && !ROLE_HEAD.test(plain) && (STOP_HEAD.test(plain) || STOP_HEAD.test(lines[i]))) break;
    if (META.test(plain)) {
      i += 1;
      if (lines[i] && lines[i].length <= 80 && !ROLE_HEAD.test(plainLine(lines[i]))) i += 1;
      continue;
    }
    if (!isNoise(lines[i])) out.push(lines[i]);
    i += 1;
    if (out.join("\n").length > 4000) break;
  }
  return out;
}

function preamble(lines: string[], start: number, title: string): string[] {
  const titleAt = lines.findIndex((l) => titleIn(l, title));
  const from = titleAt >= 0 ? titleAt + 1 : 0;
  const out: string[] = [];
  let i = from;
  while (i < start) {
    const plain = plainLine(lines[i]);
    if (META.test(plain)) {
      i += 1;
      if (lines[i] && lines[i].length <= 80) i += 1;
      continue;
    }
    if (!isNoise(lines[i]) && plain.length >= 40 && !isJobTitle(plain)) out.push(lines[i]);
    i += 1;
    if (out.length >= 2) break;
  }
  return out;
}

/** Role-only text: overview, responsibilities, and what the posting is hiring for. */
export function descriptionFromJobPage(markdown: string, title: string): string {
  if (!markdown.trim() || isCareersIndex(markdown)) return "";
  const lines = pageLines(markdown);
  const start = lines.findIndex((l) => ROLE_HEAD.test(plainLine(l)));
  const body = start >= 0 ? [...preamble(lines, start, title), ...collectRoleLines(lines, start)] : singlePostingBody(lines, title);
  const meaningful = body.filter((l) => l.length > 40 || /^[-*•]/.test(l));
  if (!meaningful.length) return "";
  return body.join("\n").trim().slice(0, 4000);
}

function singlePostingBody(lines: string[], title: string): string[] {
  const titleAt = lines.findIndex((l) => titleIn(l, title));
  const out: string[] = [];
  let i = titleAt >= 0 ? titleAt + 1 : 0;
  while (i < lines.length) {
    const plain = plainLine(lines[i]);
    if (STOP_HEAD.test(plain)) break;
    if (isJobTitle(plain) && lines[i + 1] && LOCATION_LINE.test(plainLine(lines[i + 1])) && !titleIn(plain, title)) break;
    if (META.test(plain)) {
      i += 1;
      if (lines[i] && lines[i].length <= 80 && !ROLE_HEAD.test(plainLine(lines[i]))) i += 1;
      continue;
    }
    if (!isNoise(lines[i])) out.push(lines[i]);
    i += 1;
    if (out.join("\n").length > 4000) break;
  }
  return out;
}

function matchScore(candidate: string, title: string): number {
  const head = norm(candidate).split(/[|\-–—]/)[0]?.trim() ?? "";
  const want = norm(title);
  if (!head || !want) return 0;
  if (head === want) return 3;
  if (head.startsWith(`${want} `)) return 2;
  if (titleIn(candidate, title)) return 1;
  return 0;
}

function pageLabels(page: { title: string | null; text: string }): string[] {
  const labels = [page.title ?? ""];
  for (const line of pageLines(page.text).slice(0, 40)) {
    if (/^#{1,3}\s+\S/.test(line) || /^\*\*[^*]{3,80}\*\*$/.test(line)) labels.push(plainLine(line));
  }
  return labels;
}

/** Pair each title with its own posting. The careers index never becomes the description. */
export function attachJobDescriptions(
  roles: ParsedRole[],
  pages: { title: string | null; text: string }[],
): ParsedRole[] {
  const used = new Set<number>();
  const byTitle = new Map<string, string>();
  const ordered = [...roles].sort((a, b) => b.title.length - a.title.length);
  for (const role of ordered) {
    let best = -1;
    let bestScore = 0;
    pages.forEach((page, index) => {
      if (used.has(index) || !page.text.trim() || isCareersIndex(page.text)) return;
      const score = pageLabels(page).reduce((max, label) => Math.max(max, matchScore(label, role.title)), 0);
      if (score > bestScore) {
        bestScore = score;
        best = index;
      }
    });
    if (best < 0) continue;
    used.add(best);
    const jd = descriptionFromJobPage(pages[best].text, role.title);
    if (jd) byTitle.set(role.title.toLowerCase(), jd);
  }
  return roles.map((role) => {
    const jd = byTitle.get(role.title.toLowerCase());
    return jd ? { ...role, mustHaves: jd } : role;
  });
}

function samePath(a: string, b: string): boolean {
  try {
    const left = new URL(a);
    const right = new URL(b);
    return left.hostname === right.hostname && left.pathname.replace(/\/$/, "") === right.pathname.replace(/\/$/, "");
  } catch {
    return a === b;
  }
}

function postingRank(url: URL): number {
  const parts = url.pathname.split("/").filter(Boolean);
  const path = url.pathname.toLowerCase();
  if (/\/apply\/[^/]+\/[^/]+/.test(path)) return 5;
  if (/\/jobs\/[^/]+\/[0-9a-f]{8}-/.test(path)) return 5;
  if (/\/jobs\/\d+/.test(path)) return 5;
  if (parts.length >= 2 && /ashbyhq|lever\.co|workable/.test(url.hostname)) return 4;
  if (/\/jobs\/.+/.test(path) && parts.length >= 2) return 3;
  if (parts.length >= 2 && !/\/careers\/?$/.test(path)) return 1;
  return 0;
}

function isListingUrl(url: URL, boardUrl: string): boolean {
  if (samePath(url.toString(), boardUrl)) return true;
  const path = url.pathname.replace(/\/$/, "");
  if (!path || /^\/(careers|jobs|openings)$/i.test(path)) return true;
  if (/dover/.test(url.hostname) && /\/careers\//i.test(path)) return true;
  return false;
}

/** Individual posting URLs, never the careers index. Real job links come first. */
export function jobPostingLinks(links: string[], boardUrl: string, pageText = ""): string[] {
  let host = "";
  try {
    host = new URL(boardUrl).hostname;
  } catch {
    return [];
  }
  const rawLinks = [...links];
  for (const match of pageText.matchAll(/https?:\/\/[^\s<>"')\]]+/gi)) rawLinks.push(match[0]);

  const ranked: { href: string; rank: number }[] = [];
  const seen = new Set<string>();
  for (const raw of rawLinks) {
    let url: URL;
    try {
      url = new URL(raw, boardUrl);
    } catch {
      continue;
    }
    url.hash = "";
    const href = url.toString();
    if (seen.has(href) || isListingUrl(url, boardUrl)) continue;
    if (/\.(png|jpe?g|svg|css|js|ico|pdf)$/i.test(url.pathname)) continue;
    if (/linkedin|twitter|x\.com|instagram|facebook|youtube|github/.test(url.hostname)) continue;
    const sameSite = url.hostname === host || url.hostname.endsWith(`.${host}`);
    const ats = /dover|ashbyhq|greenhouse|lever\.co|workable/.test(url.hostname);
    if (!sameSite && !ats) continue;
    const rank = postingRank(url);
    if (rank < 1) continue;
    seen.add(href);
    ranked.push({ href, rank });
  }
  ranked.sort((a, b) => b.rank - a.rank);
  return ranked.slice(0, 20).map((item) => item.href);
}
